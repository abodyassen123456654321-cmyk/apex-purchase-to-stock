-- P2S Purchase-to-Stock
-- Data model: tables, constraints, indexes, sequences, audit triggers

create table p2s_users (
    user_id        number generated by default on null as identity,
    username       varchar2(100)  not null,
    full_name      varchar2(200)  not null,
    email          varchar2(255),
    role_code      varchar2(20)   not null,
    is_active      varchar2(1)    default 'Y' not null,
    created_by     varchar2(255),
    created_on     timestamp with local time zone,
    updated_by     varchar2(255),
    updated_on     timestamp with local time zone,
    constraint p2s_users_pk        primary key (user_id),
    constraint p2s_users_uk        unique (username),
    constraint p2s_users_upper_ck  check (username = upper(username)),
    constraint p2s_users_role_ck   check (role_code in ('REQUESTER','MANAGER','FINANCE','STOREKEEPER','ADMIN')),
    constraint p2s_users_active_ck check (is_active in ('Y','N'))
);

create table p2s_suppliers (
    supplier_id    number generated by default on null as identity,
    supplier_code  varchar2(20)   not null,
    supplier_name  varchar2(200)  not null,
    email          varchar2(255),
    phone          varchar2(50),
    is_active      varchar2(1)    default 'Y' not null,
    created_by     varchar2(255),
    created_on     timestamp with local time zone,
    updated_by     varchar2(255),
    updated_on     timestamp with local time zone,
    constraint p2s_suppliers_pk        primary key (supplier_id),
    constraint p2s_suppliers_uk        unique (supplier_code),
    constraint p2s_suppliers_active_ck check (is_active in ('Y','N'))
);

create table p2s_warehouses (
    warehouse_id   number generated by default on null as identity,
    warehouse_code varchar2(20)   not null,
    warehouse_name varchar2(200)  not null,
    is_active      varchar2(1)    default 'Y' not null,
    created_by     varchar2(255),
    created_on     timestamp with local time zone,
    updated_by     varchar2(255),
    updated_on     timestamp with local time zone,
    constraint p2s_warehouses_pk        primary key (warehouse_id),
    constraint p2s_warehouses_uk        unique (warehouse_code),
    constraint p2s_warehouses_active_ck check (is_active in ('Y','N'))
);

create table p2s_items (
    item_id        number generated by default on null as identity,
    item_code      varchar2(30)   not null,
    item_name      varchar2(200)  not null,
    uom            varchar2(10)   not null,
    standard_price number(12,2)   default 0 not null,
    reorder_level  number(12,3)   default 0 not null,
    is_active      varchar2(1)    default 'Y' not null,
    created_by     varchar2(255),
    created_on     timestamp with local time zone,
    updated_by     varchar2(255),
    updated_on     timestamp with local time zone,
    constraint p2s_items_pk        primary key (item_id),
    constraint p2s_items_uk        unique (item_code),
    constraint p2s_items_price_ck  check (standard_price >= 0),
    constraint p2s_items_reord_ck  check (reorder_level >= 0),
    constraint p2s_items_active_ck check (is_active in ('Y','N'))
);

create table p2s_approval_rules (
    rule_id          number generated by default on null as identity,
    approval_level   number(2)      not null,
    approver_role    varchar2(20)   not null,
    threshold_amount number(14,2)   default 0 not null,
    is_active        varchar2(1)    default 'Y' not null,
    created_by       varchar2(255),
    created_on       timestamp with local time zone,
    updated_by       varchar2(255),
    updated_on       timestamp with local time zone,
    constraint p2s_appr_rules_pk        primary key (rule_id),
    constraint p2s_appr_rules_uk        unique (approval_level),
    constraint p2s_appr_rules_role_ck   check (approver_role in ('MANAGER','FINANCE','ADMIN')),
    constraint p2s_appr_rules_thr_ck    check (threshold_amount >= 0),
    constraint p2s_appr_rules_active_ck check (is_active in ('Y','N'))
);

create table p2s_pr_headers (
    pr_id          number generated by default on null as identity,
    pr_number      varchar2(20)   not null,
    requester_id   number         not null,
    warehouse_id   number         not null,
    request_date   date           default trunc(sysdate) not null,
    needed_by_date date,
    justification  varchar2(1000),
    status         varchar2(20)   default 'DRAFT' not null,
    total_amount   number(14,2)   default 0 not null,
    submitted_on   timestamp with local time zone,
    created_by     varchar2(255),
    created_on     timestamp with local time zone,
    updated_by     varchar2(255),
    updated_on     timestamp with local time zone,
    constraint p2s_pr_pk         primary key (pr_id),
    constraint p2s_pr_uk         unique (pr_number),
    constraint p2s_pr_req_fk     foreign key (requester_id) references p2s_users (user_id),
    constraint p2s_pr_wh_fk      foreign key (warehouse_id) references p2s_warehouses (warehouse_id),
    constraint p2s_pr_status_ck  check (status in ('DRAFT','SUBMITTED','APPROVED','REJECTED','CONVERTED','CANCELLED')),
    constraint p2s_pr_total_ck   check (total_amount >= 0),
    constraint p2s_pr_dates_ck   check (needed_by_date is null or needed_by_date >= request_date)
);

create table p2s_pr_lines (
    pr_line_id     number generated by default on null as identity,
    pr_id          number         not null,
    line_no        number(4)      not null,
    item_id        number         not null,
    quantity       number(12,3)   not null,
    est_unit_price number(12,2)   not null,
    line_amount    number(14,2)   generated always as (round(quantity * est_unit_price, 2)) virtual,
    notes          varchar2(500),
    created_by     varchar2(255),
    created_on     timestamp with local time zone,
    updated_by     varchar2(255),
    updated_on     timestamp with local time zone,
    constraint p2s_prl_pk        primary key (pr_line_id),
    constraint p2s_prl_pr_fk     foreign key (pr_id)   references p2s_pr_headers (pr_id) on delete cascade,
    constraint p2s_prl_item_fk   foreign key (item_id) references p2s_items (item_id),
    constraint p2s_prl_line_uk   unique (pr_id, line_no),
    constraint p2s_prl_item_uk   unique (pr_id, item_id),
    constraint p2s_prl_qty_ck    check (quantity > 0),
    constraint p2s_prl_price_ck  check (est_unit_price >= 0)
);

create table p2s_pr_approvals (
    approval_id    number generated by default on null as identity,
    pr_id          number         not null,
    approval_level number(2)      not null,
    approver_role  varchar2(20)   not null,
    status         varchar2(20)   default 'PENDING' not null,
    action_by_id   number,
    action_on      timestamp with local time zone,
    comments       varchar2(1000),
    created_by     varchar2(255),
    created_on     timestamp with local time zone,
    updated_by     varchar2(255),
    updated_on     timestamp with local time zone,
    constraint p2s_pra_pk          primary key (approval_id),
    constraint p2s_pra_pr_fk       foreign key (pr_id)        references p2s_pr_headers (pr_id) on delete cascade,
    constraint p2s_pra_user_fk     foreign key (action_by_id) references p2s_users (user_id),
    constraint p2s_pra_level_uk    unique (pr_id, approval_level),
    constraint p2s_pra_status_ck   check (status in ('PENDING','APPROVED','REJECTED')),
    constraint p2s_pra_reject_ck   check (status <> 'REJECTED' or comments is not null),
    constraint p2s_pra_action_ck   check (status = 'PENDING' or (action_by_id is not null and action_on is not null))
);

create table p2s_po_headers (
    po_id          number generated by default on null as identity,
    po_number      varchar2(20)   not null,
    pr_id          number         not null,
    supplier_id    number         not null,
    order_date     date           default trunc(sysdate) not null,
    expected_date  date,
    status         varchar2(20)   default 'OPEN' not null,
    total_amount   number(14,2)   default 0 not null,
    created_by     varchar2(255),
    created_on     timestamp with local time zone,
    updated_by     varchar2(255),
    updated_on     timestamp with local time zone,
    constraint p2s_po_pk         primary key (po_id),
    constraint p2s_po_uk         unique (po_number),
    constraint p2s_po_pr_uk      unique (pr_id),
    constraint p2s_po_pr_fk      foreign key (pr_id)       references p2s_pr_headers (pr_id),
    constraint p2s_po_sup_fk     foreign key (supplier_id) references p2s_suppliers (supplier_id),
    constraint p2s_po_status_ck  check (status in ('OPEN','PARTIAL','RECEIVED','CANCELLED')),
    constraint p2s_po_total_ck   check (total_amount >= 0),
    constraint p2s_po_dates_ck   check (expected_date is null or expected_date >= order_date)
);

create table p2s_po_lines (
    po_line_id     number generated by default on null as identity,
    po_id          number         not null,
    line_no        number(4)      not null,
    pr_line_id     number,
    item_id        number         not null,
    qty_ordered    number(12,3)   not null,
    unit_price     number(12,2)   not null,
    qty_received   number(12,3)   default 0 not null,
    line_amount    number(14,2)   generated always as (round(qty_ordered * unit_price, 2)) virtual,
    created_by     varchar2(255),
    created_on     timestamp with local time zone,
    updated_by     varchar2(255),
    updated_on     timestamp with local time zone,
    constraint p2s_pol_pk        primary key (po_line_id),
    constraint p2s_pol_po_fk     foreign key (po_id)      references p2s_po_headers (po_id) on delete cascade,
    constraint p2s_pol_prl_fk    foreign key (pr_line_id) references p2s_pr_lines (pr_line_id),
    constraint p2s_pol_item_fk   foreign key (item_id)    references p2s_items (item_id),
    constraint p2s_pol_line_uk   unique (po_id, line_no),
    constraint p2s_pol_qty_ck    check (qty_ordered > 0),
    constraint p2s_pol_price_ck  check (unit_price >= 0),
    constraint p2s_pol_recv_ck   check (qty_received between 0 and qty_ordered)
);

create table p2s_grn_headers (
    grn_id         number generated by default on null as identity,
    grn_number     varchar2(20)   not null,
    po_id          number         not null,
    warehouse_id   number         not null,
    receipt_date   date           default trunc(sysdate) not null,
    received_by_id number         not null,
    notes          varchar2(1000),
    status         varchar2(20)   default 'DRAFT' not null,
    posted_on      timestamp with local time zone,
    created_by     varchar2(255),
    created_on     timestamp with local time zone,
    updated_by     varchar2(255),
    updated_on     timestamp with local time zone,
    constraint p2s_grn_pk         primary key (grn_id),
    constraint p2s_grn_uk         unique (grn_number),
    constraint p2s_grn_po_fk      foreign key (po_id)          references p2s_po_headers (po_id),
    constraint p2s_grn_wh_fk      foreign key (warehouse_id)   references p2s_warehouses (warehouse_id),
    constraint p2s_grn_user_fk    foreign key (received_by_id) references p2s_users (user_id),
    constraint p2s_grn_status_ck  check (status in ('DRAFT','POSTED')),
    constraint p2s_grn_posted_ck  check (status = 'DRAFT' or posted_on is not null)
);

create table p2s_grn_lines (
    grn_line_id    number generated by default on null as identity,
    grn_id         number         not null,
    po_line_id     number         not null,
    qty_received   number(12,3)   not null,
    created_by     varchar2(255),
    created_on     timestamp with local time zone,
    updated_by     varchar2(255),
    updated_on     timestamp with local time zone,
    constraint p2s_grnl_pk       primary key (grn_line_id),
    constraint p2s_grnl_grn_fk   foreign key (grn_id)     references p2s_grn_headers (grn_id) on delete cascade,
    constraint p2s_grnl_pol_fk   foreign key (po_line_id) references p2s_po_lines (po_line_id),
    constraint p2s_grnl_pol_uk   unique (grn_id, po_line_id),
    constraint p2s_grnl_qty_ck   check (qty_received > 0)
);

create table p2s_stock_balances (
    warehouse_id   number         not null,
    item_id        number         not null,
    qty_on_hand    number(14,3)   default 0 not null,
    created_by     varchar2(255),
    created_on     timestamp with local time zone,
    updated_by     varchar2(255),
    updated_on     timestamp with local time zone,
    constraint p2s_stb_pk        primary key (warehouse_id, item_id),
    constraint p2s_stb_wh_fk     foreign key (warehouse_id) references p2s_warehouses (warehouse_id),
    constraint p2s_stb_item_fk   foreign key (item_id)      references p2s_items (item_id),
    constraint p2s_stb_qty_ck    check (qty_on_hand >= 0)
);

create table p2s_stock_movements (
    movement_id    number generated by default on null as identity,
    movement_date  timestamp with local time zone default systimestamp not null,
    movement_type  varchar2(20)   not null,
    warehouse_id   number         not null,
    item_id        number         not null,
    quantity       number(14,3)   not null,
    balance_after  number(14,3)   not null,
    ref_type       varchar2(20),
    ref_id         number,
    reason         varchar2(500),
    created_by     varchar2(255),
    created_on     timestamp with local time zone,
    updated_by     varchar2(255),
    updated_on     timestamp with local time zone,
    constraint p2s_stm_pk        primary key (movement_id),
    constraint p2s_stm_wh_fk     foreign key (warehouse_id) references p2s_warehouses (warehouse_id),
    constraint p2s_stm_item_fk   foreign key (item_id)      references p2s_items (item_id),
    constraint p2s_stm_type_ck   check (movement_type in ('RECEIPT','ISSUE','ADJUST_IN','ADJUST_OUT')),
    constraint p2s_stm_sign_ck   check (
           (movement_type in ('RECEIPT','ADJUST_IN')  and quantity > 0)
        or (movement_type in ('ISSUE','ADJUST_OUT')   and quantity < 0)),
    constraint p2s_stm_bal_ck    check (balance_after >= 0)
);

create table p2s_error_log (
    log_id          number generated by default on null as identity,
    log_time        timestamp with local time zone default systimestamp not null,
    app_user        varchar2(255),
    module_name     varchar2(200),
    error_code      number,
    error_message   varchar2(4000),
    error_backtrace varchar2(4000),
    context_info    varchar2(4000),
    constraint p2s_error_log_pk primary key (log_id)
);

