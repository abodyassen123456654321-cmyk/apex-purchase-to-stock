begin
    for t in (
        select table_name
          from user_tab_columns
         where column_name = 'CREATED_BY'
           and table_name like 'P2S\_%' escape '\'
    ) loop
        execute immediate
            'create or replace trigger ' || t.table_name || '_BIU' ||
            ' before insert or update on ' || t.table_name ||
            ' for each row' ||
            q'[
begin
    if inserting then
        :new.created_on := systimestamp;
        :new.created_by := coalesce(sys_context('APEX$SESSION','APP_USER'), user);
    end if;
    :new.updated_on := systimestamp;
    :new.updated_by := coalesce(sys_context('APEX$SESSION','APP_USER'), user);
end;]';
    end loop;
end;
/

select object_type, status, count(*) cnt
  from user_objects
 where object_name like 'P2S\_%' escape '\'
 group by object_type, status
 order by object_type;
